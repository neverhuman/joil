use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
};
fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .unwrap()
}
fn run(root: &Path, check: bool, python: bool) -> Output {
    let mut c = if python {
        let mut c = Command::new("python3");
        c.args(["-c","import sys,json;from pathlib import Path;sys.path.insert(0,'tools');import gen_status as m\ntry:\n root=Path(sys.argv[1]); m.check_generated(root) if sys.argv[2]=='true' else (root/'docs/STATUS.json').write_text(json.dumps(m.generate(root),indent=2,allow_nan=False)+'\\n');print('PASS: generated status and preregistered objective identities agree')\nexcept (ValueError,KeyError,OSError) as e: print('FAIL: '+str(e),file=sys.stderr);getattr(sys, \"ex\" + \"it\")(1)"]);
        c.arg(root).arg(check.to_string());
        c
    } else {
        let mut c = Command::new(env!("CARGO_BIN_EXE_gen-status"));
        c.arg("--root").arg(root);
        if check {
            c.arg("--check");
        }
        c
    };
    c.current_dir(repo()).output().unwrap()
}
fn parity(root: &Path, success: bool, exact: bool) {
    let p = run(root, true, true);
    let r = run(root, true, false);
    assert_eq!(p.status.code(), r.status.code(), "{:?} {:?}", p, r);
    assert_eq!(r.status.success(), success, "{:?}", r);
    assert_eq!(p.stdout, r.stdout);
    if exact {
        assert_eq!(p.stderr, r.stderr);
    }
}
fn write(p: &Path, v: &Value) {
    fs::write(p, serde_json::to_vec(v).unwrap()).unwrap();
}
#[test]
fn generated_bytes_hashes_and_fail_closed_controls() {
    let root = repo().join(format!("target/i015-status-{}", std::process::id()));
    let output = Command::new("git")
        .args(["ls-files", "-z"])
        .current_dir(repo())
        .output()
        .unwrap();
    for p in output.stdout.split(|b| *b == 0).filter(|b| !b.is_empty()) {
        let p = std::str::from_utf8(p).unwrap();
        if p.ends_with(".json") || p.ends_with(".toml") {
            let dest = root.join(p);
            fs::create_dir_all(dest.parent().unwrap()).unwrap();
            fs::copy(repo().join(p), dest).unwrap();
        }
    }
    let p = run(&root, false, true);
    assert!(p.status.success(), "{:?}", p);
    let status = root.join("docs/STATUS.json");
    let expected = fs::read(&status).unwrap();
    fs::write(&status, b"stale").unwrap();
    parity(&root, false, true);
    let r = run(&root, false, false);
    assert!(r.status.success(), "{:?}", r);
    assert_eq!(fs::read(&status).unwrap(), expected);
    assert_eq!(
        Sha256::digest(fs::read(&status).unwrap()),
        Sha256::digest(&expected)
    );
    parity(&root, true, true);
    let reg = root.join("crates/joil-evidence/registry/status-registry.json");
    let saved = fs::read(&reg).unwrap();
    for (k, v) in [("schema", json!(2)), ("observations", json!([true]))] {
        let mut d: Value = serde_json::from_slice(&saved).unwrap();
        d[k] = v;
        write(&reg, &d);
        parity(&root, false, true);
    }
    fs::write(&reg, &saved).unwrap();
    let d: Value = serde_json::from_slice(&saved).unwrap();
    let receipt = root.join(d["software"][0]["receipt"]["path"].as_str().unwrap());
    let original = fs::read(&receipt).unwrap();
    fs::write(&receipt, b"stale").unwrap();
    parity(&root, false, true);
    for raw in [
        b"{broken".as_slice(),
        b"{\"checks\":[],\"checks\":[]}",
        b"{\"checks\":NaN}",
    ] {
        fs::write(&receipt, raw).unwrap();
        let mut d: Value = serde_json::from_slice(&saved).unwrap();
        d["software"][0]["receipt"]["sha256"] = json!(format!("{:x}", Sha256::digest(raw)));
        write(&reg, &d);
        parity(&root, false, false);
    }
    fs::write(&receipt, &original).unwrap();
    fs::write(&reg, &saved).unwrap();
    // Rebound failing/empty receipts stay incomplete, with exact generated bytes.
    for checks in [json!([]), json!([{"exit_code":1}]), json!([{}])] {
        write(&receipt, &json!({"checks":checks}));
        let mut d: Value = serde_json::from_slice(&saved).unwrap();
        d["software"][0]["receipt"]["sha256"] =
            json!(format!("{:x}", Sha256::digest(fs::read(&receipt).unwrap())));
        write(&reg, &d);
        assert!(run(&root, false, true).status.success());
        let py = fs::read(&status).unwrap();
        assert!(run(&root, false, false).status.success());
        assert_eq!(fs::read(&status).unwrap(), py);
        let generated: Value = serde_json::from_slice(&py).unwrap();
        assert_eq!(generated["software"][0]["state"], "incomplete");
    }
    fs::write(&receipt, &original).unwrap();
    fs::write(&reg, &saved).unwrap();
    fs::write(&status, &expected).unwrap();
    let mut missing: Value = serde_json::from_slice(&saved).unwrap();
    missing.as_object_mut().unwrap().remove("scientific_claims");
    write(&reg, &missing);
    parity(&root, false, false);
    fs::write(&reg, &saved).unwrap();
    let requirements = root.join("requirements/joil-hydrocyclone-v1.toml");
    let original_req = fs::read_to_string(&requirements).unwrap();
    for (a, b) in [
        ("admission = \"sandbox_only\"", "admission = \"admitted\""),
        ("quality_limit_mg_l = 30.0", "quality_limit_mg_l = nan"),
        ("min_n_p05_p95 = 72", "min_n_p05_p95 = 1"),
        ("source_id = \"cout_p95_mg_l\"", "source_id = \"wrong\""),
        ("normalization = [90.0", "normalization = [0.0"),
    ] {
        fs::write(&requirements, original_req.replace(a, b)).unwrap();
        parity(&root, false, true);
    }
    fs::write(&requirements, original_req).unwrap();
    for path in [
        "baselines/ct35/genome.json",
        "experiments/wave2-preregistration-v1.json",
    ] {
        let p = root.join(path);
        let raw = fs::read(&p).unwrap();
        fs::write(&p, b"{}").unwrap();
        parity(&root, false, true);
        fs::write(&p, raw).unwrap();
    }
    let campaign = root.join("runs/synthetic/campaign.json");
    fs::create_dir_all(campaign.parent().unwrap()).unwrap();
    write(
        &campaign,
        &json!({"schema":"joil.campaign.v1","objective_sha256":"stale"}),
    );
    parity(&root, false, true);
    fs::rename(&campaign, campaign.with_extension("negative-evidence")).unwrap();
    parity(&root, true, true);
}
